package com.collegemanagement.server;

import com.collegemanagement.model.*;
import javax.servlet.http.HttpServletRequest;
import java.io.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.*;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class JspRenderer {
    private File webappDir;

    public JspRenderer(File webappDir) {
        this.webappDir = webappDir;
    }

    public String render(String jspPath, HttpServletRequest request) throws IOException {
        File file = new File(webappDir, jspPath.startsWith("/") ? jspPath.substring(1) : jspPath);
        if (!file.exists()) {
            return "<html><body><h2>404 - View Not Found: " + jspPath + "</h2></body></html>";
        }

        String content = new String(Files.readAllBytes(file.toPath()), StandardCharsets.UTF_8);
        content = processIncludes(content, file.getParentFile());
        content = processExpressions(content, request);
        return content;
    }

    private String processIncludes(String content, File baseDir) {
        Pattern pattern = Pattern.compile("<%@\\s*include\\s+file=[\"']([^\"']+)[\"']\\s*%>");
        Matcher matcher = pattern.matcher(content);
        StringBuffer sb = new StringBuffer();
        while (matcher.find()) {
            String incFile = matcher.group(1);
            File target = new File(baseDir, incFile);
            if (target.exists()) {
                try {
                    String incContent = new String(Files.readAllBytes(target.toPath()), StandardCharsets.UTF_8);
                    incContent = processIncludes(incContent, target.getParentFile());
                    matcher.appendReplacement(sb, Matcher.quoteReplacement(incContent));
                    continue;
                } catch (IOException ignored) {}
            }
            matcher.appendReplacement(sb, "<!-- Missing include: " + incFile + " -->");
        }
        matcher.appendTail(sb);
        return sb.toString();
    }

    private String processExpressions(String content, HttpServletRequest request) {
        // Strip out page directives
        content = content.replaceAll("<%@\\s*page[^%>]*%>", "");

        // Render dynamic variables: ${var}
        Pattern elPattern = Pattern.compile("\\$\\{([^}]+)\\}");
        Matcher matcher = elPattern.matcher(content);
        StringBuffer sb = new StringBuffer();
        while (matcher.find()) {
            String expr = matcher.group(1).trim();
            String val = evaluateExpression(expr, request);
            matcher.appendReplacement(sb, Matcher.quoteReplacement(val != null ? val : ""));
        }
        matcher.appendTail(sb);

        // Render dynamic body tags generated by server
        String rendered = sb.toString();
        rendered = renderDynamicLoops(rendered, request);

        // Strip remaining raw scriptlet markers if present for clean HTML output
        rendered = rendered.replaceAll("<%--[\\s\\S]*?--%>", "");
        rendered = rendered.replaceAll("<%[\\s\\S]*?%>", "");

        return rendered;
    }

    private String evaluateExpression(String expr, HttpServletRequest request) {
        if ("pageContext.request.contextPath".equals(expr)) {
            return request.getContextPath();
        }

        if (expr.contains(".")) {
            String[] parts = expr.split("\\.", 2);
            Object obj = request.getAttribute(parts[0]);
            if (obj == null && request.getSession(false) != null) {
                obj = request.getSession(false).getAttribute(parts[0]);
            }
            if (obj != null) {
                return extractProperty(obj, parts[1]);
            }
            return "";
        }

        Object obj = request.getAttribute(expr);
        if (obj == null && request.getSession(false) != null) {
            obj = request.getSession(false).getAttribute(expr);
        }
        return obj != null ? obj.toString() : "";
    }

    private String extractProperty(Object obj, String prop) {
        if (obj instanceof Student) {
            Student s = (Student) obj;
            switch (prop) {
                case "studentId": return String.valueOf(s.getStudentId());
                case "firstName": return s.getFirstName();
                case "lastName": return s.getLastName();
                case "fullName": return s.getFullName();
                case "dateOfBirth": return s.getDateOfBirth();
                case "gender": return s.getGender();
                case "admissionDate": return s.getAdmissionDate();
                case "className": return s.getClassName();
                case "email": return s.getEmail();
                case "phoneNumber": return s.getPhoneNumber();
                case "address": return s.getAddress();
                case "parentName": return s.getParentName();
                case "registrationNumber": return s.getRegistrationNumber();
                case "status": return s.getStatus();
            }
        } else if (obj instanceof User) {
            User u = (User) obj;
            switch (prop) {
                case "username": return u.getUsername();
                case "fullName": return u.getFullName();
                case "role": return u.getRole();
                case "email": return u.getEmail();
            }
        } else if (obj instanceof ReportCard) {
            ReportCard rc = (ReportCard) obj;
            switch (prop) {
                case "studentId": return String.valueOf(rc.getStudentId());
                case "studentName": return rc.getStudentName();
                case "className": return rc.getClassName();
                case "examName": return rc.getExamName();
                case "totalMarksObtained": return String.valueOf(rc.getTotalMarksObtained());
                case "totalMaxMarks": return String.valueOf(rc.getTotalMaxMarks());
                case "overallPercentage": return String.valueOf(rc.getOverallPercentage());
                case "overallGrade": return rc.getOverallGrade();
                case "status": return rc.getStatus();
            }
        }
        return "";
    }

    @SuppressWarnings("unchecked")
    private String renderDynamicLoops(String html, HttpServletRequest req) {
        // Students table generator
        if (html.contains("<!-- ##STUDENTS_TABLE_ROWS## -->")) {
            List<Student> students = (List<Student>) req.getAttribute("students");
            StringBuilder rows = new StringBuilder();
            if (students == null || students.isEmpty()) {
                rows.append("<tr><td colspan='7' class='text-center py-4 text-muted'><i class='bi bi-inbox fs-3 d-block mb-2'></i>No registered students found matching your criteria.</td></tr>");
            } else {
                for (Student s : students) {
                    rows.append("<tr>")
                        .append("<td class='fw-semibold text-primary'>").append(s.getRegistrationNumber()).append("</td>")
                        .append("<td>")
                            .append("<div class='d-flex align-items-center'>")
                                .append("<div class='avatar-sm rounded-circle me-2 d-flex align-items-center justify-content-center text-white bg-primary bg-gradient' style='width:36px;height:36px;font-size:14px;font-weight:600;'>")
                                    .append(s.getFirstName().isEmpty() ? "S" : s.getFirstName().substring(0, 1))
                                .append("</div>")
                                .append("<div>")
                                    .append("<div class='fw-semibold text-dark'>").append(s.getFullName()).append("</div>")
                                    .append("<div class='small text-muted'>").append(s.getEmail()).append("</div>")
                                .append("</div>")
                            .append("</div>")
                        .append("</td>")
                        .append("<td><span class='badge bg-light text-dark border'>").append(s.getClassName()).append("</span></td>")
                        .append("<td><span class='badge bg-").append("Female".equalsIgnoreCase(s.getGender()) ? "info text-dark" : "secondary").append("'>").append(s.getGender()).append("</span></td>")
                        .append("<td class='small text-muted'>").append(s.getAdmissionDate()).append("</td>")
                        .append("<td><span class='badge bg-success-subtle text-success border border-success-subtle px-2 py-1'><i class='bi bi-check-circle me-1'></i>Enrolled</span></td>")
                        .append("<td class='text-end'>")
                            .append("<div class='btn-group btn-group-sm'>")
                                .append("<a href='").append(req.getContextPath()).append("/student/profile?id=").append(s.getStudentId()).append("' class='btn btn-outline-primary' title='View Profile'><i class='bi bi-eye'></i></a>")
                                .append("<a href='").append(req.getContextPath()).append("/student/edit?id=").append(s.getStudentId()).append("' class='btn btn-outline-secondary' title='Edit'><i class='bi bi-pencil'></i></a>")
                                .append("<a href='").append(req.getContextPath()).append("/report-card?id=").append(s.getStudentId()).append("' class='btn btn-outline-info' title='Report Card'><i class='bi bi-file-earmark-text'></i></a>")
                                .append("<a href='javascript:void(0)' onclick='confirmDelete(").append(s.getStudentId()).append(", \"").append(s.getFullName()).append("\")' class='btn btn-outline-danger' title='Delete'><i class='bi bi-trash'></i></a>")
                            .append("</div>")
                        .append("</td>")
                        .append("</tr>");
                }
            }
            html = html.replace("<!-- ##STUDENTS_TABLE_ROWS## -->", rows.toString());
        }

        // Recent students in dashboard
        if (html.contains("<!-- ##RECENT_STUDENTS_ROWS## -->")) {
            List<Student> recent = (List<Student>) req.getAttribute("recentStudents");
            StringBuilder rows = new StringBuilder();
            if (recent != null) {
                for (Student s : recent) {
                    rows.append("<tr>")
                        .append("<td class='fw-medium text-primary'>").append(s.getRegistrationNumber()).append("</td>")
                        .append("<td class='fw-semibold'>").append(s.getFullName()).append("</td>")
                        .append("<td><span class='badge bg-light text-dark border'>").append(s.getClassName()).append("</span></td>")
                        .append("<td class='text-muted small'>").append(s.getAdmissionDate()).append("</td>")
                        .append("<td class='text-end'><a href='").append(req.getContextPath()).append("/student/profile?id=").append(s.getStudentId()).append("' class='btn btn-sm btn-light border'><i class='bi bi-arrow-right'></i></a></td>")
                        .append("</tr>");
                }
            }
            html = html.replace("<!-- ##RECENT_STUDENTS_ROWS## -->", rows.toString());
        }

        // Top performers in dashboard
        if (html.contains("<!-- ##TOP_PERFORMERS_ROWS## -->")) {
            List<ReportCard> top = (List<ReportCard>) req.getAttribute("topPerformers");
            StringBuilder rows = new StringBuilder();
            if (top != null) {
                int rank = 1;
                for (ReportCard rc : top) {
                    String badgeColor = rank == 1 ? "bg-warning text-dark" : (rank == 2 ? "bg-secondary text-white" : "bg-light text-dark border");
                    rows.append("<tr>")
                        .append("<td><span class='badge ").append(badgeColor).append(" rounded-circle' style='width:24px;height:24px;line-height:16px;'>").append(rank++).append("</span></td>")
                        .append("<td class='fw-semibold'>").append(rc.getStudentName()).append("</td>")
                        .append("<td class='fw-bold text-success'>").append(rc.getOverallPercentage()).append("%</td>")
                        .append("<td><span class='badge bg-success-subtle text-success border border-success-subtle'>").append(rc.getOverallGrade()).append("</span></td>")
                        .append("<td class='text-end'><a href='").append(req.getContextPath()).append("/report-card?id=").append(rc.getStudentId()).append("' class='btn btn-sm btn-outline-primary'>Transcript</a></td>")
                        .append("</tr>");
                }
            }
            html = html.replace("<!-- ##TOP_PERFORMERS_ROWS## -->", rows.toString());
        }

        // Attendance Table Rows
        if (html.contains("<!-- ##ATTENDANCE_TABLE_ROWS## -->")) {
            List<Attendance> list = (List<Attendance>) req.getAttribute("attendanceList");
            StringBuilder rows = new StringBuilder();
            if (list == null || list.isEmpty()) {
                rows.append("<tr><td colspan='5' class='text-center py-4 text-muted'><i class='bi bi-calendar-x fs-3 d-block mb-2'></i>No attendance records found for this date.</td></tr>");
            } else {
                for (Attendance a : list) {
                    String badgeClass = "Present".equalsIgnoreCase(a.getStatus()) ? "bg-success" : 
                                       ("Absent".equalsIgnoreCase(a.getStatus()) ? "bg-danger" : "bg-warning text-dark");
                    rows.append("<tr>")
                        .append("<td class='fw-semibold text-muted'>#").append(a.getAttendanceId()).append("</td>")
                        .append("<td class='fw-semibold text-dark'>").append(a.getStudentName()).append("</td>")
                        .append("<td>").append(a.getAttendanceDate()).append("</td>")
                        .append("<td><span class='badge ").append(badgeClass).append(" px-2 py-1'>").append(a.getStatus()).append("</span></td>")
                        .append("<td class='text-end'>")
                            .append("<form method='POST' action='").append(req.getContextPath()).append("/attendance' class='d-inline-flex gap-1'>")
                                .append("<input type='hidden' name='studentId' value='").append(a.getStudentId()).append("'>")
                                .append("<input type='hidden' name='attendanceDate' value='").append(a.getAttendanceDate()).append("'>")
                                .append("<button name='status' value='Present' class='btn btn-xs btn-outline-success ").append("Present".equalsIgnoreCase(a.getStatus()) ? "active" : "").append("'>P</button>")
                                .append("<button name='status' value='Absent' class='btn btn-xs btn-outline-danger ").append("Absent".equalsIgnoreCase(a.getStatus()) ? "active" : "").append("'>A</button>")
                                .append("<button name='status' value='Late' class='btn btn-xs btn-outline-warning ").append("Late".equalsIgnoreCase(a.getStatus()) ? "active" : "").append("'>L</button>")
                            .append("</form>")
                        .append("</td>")
                        .append("</tr>");
                }
            }
            html = html.replace("<!-- ##ATTENDANCE_TABLE_ROWS## -->", rows.toString());
        }

        // Results / Ranking Table Rows
        if (html.contains("<!-- ##RESULTS_TABLE_ROWS## -->")) {
            List<ReportCard> rankings = (List<ReportCard>) req.getAttribute("rankings");
            StringBuilder rows = new StringBuilder();
            if (rankings != null) {
                int r = 1;
                for (ReportCard rc : rankings) {
                    rows.append("<tr>")
                        .append("<td class='fw-bold'>#").append(r++).append("</td>")
                        .append("<td class='fw-semibold text-primary'>").append(rc.getStudentName()).append("</td>")
                        .append("<td><span class='badge bg-light text-dark border'>").append(rc.getClassName()).append("</span></td>")
                        .append("<td class='fw-bold'>").append(rc.getTotalMarksObtained()).append(" / ").append(rc.getTotalMaxMarks()).append("</td>")
                        .append("<td class='fw-bold text-success'>").append(rc.getOverallPercentage()).append("%</td>")
                        .append("<td><span class='badge bg-primary-subtle text-primary border border-primary-subtle'>").append(rc.getOverallGrade()).append("</span></td>")
                        .append("<td class='text-end'><a href='").append(req.getContextPath()).append("/report-card?id=").append(rc.getStudentId()).append("' class='btn btn-sm btn-outline-primary'><i class='bi bi-printer me-1'></i>Report Card</a></td>")
                        .append("</tr>");
                }
            }
            html = html.replace("<!-- ##RESULTS_TABLE_ROWS## -->", rows.toString());
        }

        // Student Profile Subjects and Attendance
        if (html.contains("<!-- ##STUDENT_PROFILE_SUBJECTS## -->")) {
            ReportCard rc = (ReportCard) req.getAttribute("reportCard");
            StringBuilder rows = new StringBuilder();
            if (rc != null && rc.getSubjects() != null) {
                for (ExamResult er : rc.getSubjects()) {
                    rows.append("<tr>")
                        .append("<td class='fw-semibold'>").append(er.getSubjectName()).append("</td>")
                        .append("<td>").append(er.getMarksObtained()).append(" / ").append(er.getMaxMarks()).append("</td>")
                        .append("<td class='fw-bold text-primary'>").append(er.getPercentage()).append("%</td>")
                        .append("<td><span class='badge bg-success-subtle text-success border border-success-subtle'>").append(er.getGrade()).append("</span></td>")
                        .append("<td><span class='badge bg-light text-dark border'>").append(er.getStatus()).append("</span></td>")
                        .append("</tr>");
                }
            }
            html = html.replace("<!-- ##STUDENT_PROFILE_SUBJECTS## -->", rows.toString());
        }

        // Report Card Subject Rows
        if (html.contains("<!-- ##REPORT_CARD_SUBJECT_ROWS## -->")) {
            ReportCard rc = (ReportCard) req.getAttribute("reportCard");
            StringBuilder rows = new StringBuilder();
            if (rc != null && rc.getSubjects() != null) {
                int sNo = 1;
                for (ExamResult er : rc.getSubjects()) {
                    rows.append("<tr>")
                        .append("<td class='text-center'>").append(sNo++).append("</td>")
                        .append("<td class='fw-semibold'>").append(er.getSubjectName()).append("</td>")
                        .append("<td class='text-center'>").append(er.getMaxMarks()).append("</td>")
                        .append("<td class='text-center fw-bold'>").append(er.getMarksObtained()).append("</td>")
                        .append("<td class='text-center fw-semibold text-primary'>").append(er.getPercentage()).append("%</td>")
                        .append("<td class='text-center'><span class='badge bg-light text-dark border px-2 py-1'>").append(er.getGrade()).append("</span></td>")
                        .append("<td class='text-center'><span class='badge bg-success-subtle text-success border border-success-subtle'>").append(er.getStatus()).append("</span></td>")
                        .append("</tr>");
                }
            }
            html = html.replace("<!-- ##REPORT_CARD_SUBJECT_ROWS## -->", rows.toString());
        }

        // Class options for registration & edit dropdown
        if (html.contains("<!-- ##CLASS_SELECT_OPTIONS## -->")) {
            List<CollegeClass> classes = (List<CollegeClass>) req.getAttribute("classes");
            Student stu = (Student) req.getAttribute("student");
            int selectedClassId = stu != null ? stu.getClassId() : 1;
            StringBuilder opts = new StringBuilder();
            if (classes != null) {
                for (CollegeClass cc : classes) {
                    opts.append("<option value='").append(cc.getClassId()).append("'")
                        .append(cc.getClassId() == selectedClassId ? " selected" : "")
                        .append(">")
                        .append(cc.getClassName())
                        .append("</option>");
                }
            }
            html = html.replace("<!-- ##CLASS_SELECT_OPTIONS## -->", opts.toString());
        }

        // Student select options for results & attendance
        if (html.contains("<!-- ##STUDENT_SELECT_OPTIONS## -->")) {
            List<Student> students = (List<Student>) req.getAttribute("students");
            if (students == null) students = (List<Student>) req.getAttribute("allStudents");
            StringBuilder opts = new StringBuilder();
            if (students != null) {
                for (Student s : students) {
                    opts.append("<option value='").append(s.getStudentId()).append("'>")
                        .append(s.getRegistrationNumber()).append(" - ").append(s.getFullName())
                        .append("</option>");
                }
            }
            html = html.replace("<!-- ##STUDENT_SELECT_OPTIONS## -->", opts.toString());
        }

        // Subject select options
        if (html.contains("<!-- ##SUBJECT_SELECT_OPTIONS## -->")) {
            List<Subject> subs = (List<Subject>) req.getAttribute("subjects");
            StringBuilder opts = new StringBuilder();
            if (subs != null) {
                for (Subject s : subs) {
                    opts.append("<option value='").append(s.getSubjectId()).append("'>")
                        .append(s.getSubjectName())
                        .append("</option>");
                }
            }
            html = html.replace("<!-- ##SUBJECT_SELECT_OPTIONS## -->", opts.toString());
        }

        return html;
    }
}

